/* ============================================================
   render.mjs
   The command line's way into the renderer. Loads the same four
   browser files under node, with globalThis standing in for
   window, and writes the print document to stdout.

     node render.mjs                        whole deck, landscape
     node render.mjs deck.json              a saved model instead
     node render.mjs --only cover,offer     some sections
     node render.mjs --one-pager            A4 portrait, condensed
     node render.mjs --screen               the sendable HTML deck
     node render.mjs --share                the hosted page, one file
     node render.mjs --opts opts.json       the picker's own selection

   make-pdf.py and serve.py both call this, so neither of them
   knows anything about how a deck looks.
   ============================================================ */
import { readFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));

/* The browser files are plain scripts that attach to window. Give them
   a window and they load unchanged, which is the whole point. */
globalThis.window = globalThis;

function load(rel) {
  const src = readFileSync(resolve(HERE, rel), 'utf8');
  new Function(src).call(globalThis);
}

load('deck-assets.js');                /* fonts and icons, generated */
load('brand.sunlogic.js');
load('deck-style.js');
load('deck-render.js');
load('deck.data.js');

const argv = process.argv.slice(2);

/* A flag's value is spoken for, so it cannot also be read as the model
   file. Without this, --opts opts.json loaded the selection as the deck
   and rendered nothing, which looks exactly like an empty selection. */
const taken = new Set();
const flag = (name) => {
  const i = argv.indexOf('--' + name);
  if (i < 0) return null;
  const v = argv[i + 1];
  if (v && !v.startsWith('--')) { taken.add(i + 1); return v; }
  return true;
};

/* Read every flag first, then whatever positional argument is left is
   the model. */
for (const name of ['opts', 'only', 'one-pager', 'screen', 'share']) flag(name);

const file = argv.find((a, i) =>
  !taken.has(i) && !a.startsWith('--') && /\.json$/i.test(a));
const model = file ? JSON.parse(readFileSync(resolve(file), 'utf8')) : window.SL_DECK_TEMPLATE;

/* --opts takes the selection object the picker builds, so the button and
   the command line pass the renderer the same shape. The flags below are
   the hand-typed equivalent, and --opts wins where both are given. */
const optsFile = flag('opts');
const only = flag('only');
const opts = typeof optsFile === 'string'
  ? JSON.parse(readFileSync(resolve(optsFile), 'utf8'))
  : {
      only: typeof only === 'string' ? only.split(',').map((s) => s.trim()).filter(Boolean) : null,
      onePager: !!flag('one-pager')
    };

/* --share is the page that goes on the site: the deck, the download
   picker, and no editor, as ONE file with every script inlined.
   Generated rather than copied, because the repo already has two
   copies of the document builder that have drifted apart, and a deck
   that disagrees with itself is worse than no deck. */
function sharePage(m) {
  /* The build stamps its SL_BUILD tag in front of the first `</head>` it
     finds, by plain text replace. deck-render.js carries that string in a
     JS literal, so the stamp landed inside the script and cut it short.
     `<\/head>` is the same string to JavaScript and invisible to a text
     search for the tag, which keeps the page out of the build's way
     without asking the build to understand JavaScript. */
  const shield = (js) => js.replace(/<\/(head|body|html|script)\b/gi, '<\\/$1');
  const inline = (rel) =>
    '<script>' + shield(readFileSync(resolve(HERE, rel), 'utf8')) + '<\/script>';
  const meta = m.meta || {};
  const esc = (t) => String(t == null ? '' : t)
    .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
  return '<!DOCTYPE html>\n<html lang="en-ZA">\n<head>\n<meta charset="utf-8">\n'
    + '<meta name="viewport" content="width=device-width,initial-scale=1">\n'
    + '<title>' + esc(meta.title || 'Sunlogic') + '</title>\n'
    + '<!-- Generated by tools/pitch-deck/render.mjs --share. Do not hand edit:\n'
    + '     edit the deck and run it again.\n\n'
    + '     A pitch deck is addressed to one reader. It is not for a crawler,\n'
    + '     and a link that reaches one by accident should not put it into an\n'
    + '     index. robots.txt disallows /share/ and _headers sets X-Robots-Tag\n'
    + '     and no-store on it; this is the third of the three. -->\n'
    + '<meta name="robots" content="noindex, nofollow">\n'
    + '<meta name="referrer" content="no-referrer">\n'
    + '<style>body{margin:0;background:#FFF7E9}</style>\n'
    + inline('deck-assets.js') + '\n' + inline('brand.sunlogic.js') + '\n'
    + inline('deck-style.js') + '\n' + inline('deck-render.js') + '\n'
    + inline('deck.data.js') + '\n</head>\n<body>\n'
    + '<plugin-pitch-deck view></plugin-pitch-deck>\n'
    + '<noscript><p style="font:16px/1.5 system-ui;padding:24px">'
    + 'This deck needs JavaScript. Ask us for the PDF instead: '
    + '<a href="mailto:sales@sunlogic.co.za">sales@sunlogic.co.za</a>.</p></noscript>\n'
    + inline('deck-editor.js') + '\n</body>\n</html>';
}

const out = flag('share')
  ? sharePage(model)
  : flag('screen')
    ? window.SLDeck.standalone(model, opts)
    : window.SLDeck.printDoc(model, opts);

/* A deck that breaks a house rule still renders, but say so on stderr so
   a CI run or a careless operator is told. */
const fails = window.SLDeck.checkModel(model);
if (fails.length) {
  process.stderr.write('check: ' + fails.length + ' to look at\n');
  for (const f of fails) process.stderr.write('  ' + f.rule + '  ' + f.where + '  ' + f.detail + '\n');
}

process.stdout.write(out);
